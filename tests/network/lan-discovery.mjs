// Product acceptance: real mDNS packets on a run-owned internal LAN, no Internet seeds.
import assert from 'node:assert/strict';
export async function lanDiscoveryCase({network,container,start,fixture,call,info,snapshot,until,send,evidence}) {
  const lan=await network('discovery-lan',true);
  const a=await container('lan-a',lan),b=await container('lan-b',lan);
  const silent=await container('lan-silent',lan),late=await container('lan-late',lan);
  const attacker=await container('lan-advertiser',lan);
  const original=await start(a,[],['tcp']);
  evidence.lanDiscovery={initial:original};
  await start(b,['--lan-discovery'],['tcp']);
  await start(silent,[],['tcp']);await start(late,[],['tcp']);
  await call(a,'create_identity',{name:'Alice'});await call(b,'create_identity',{name:'Bob'});
  const identity=(await snapshot(a)).identity;
  const first=await call(a,'network_settings');
  assert.equal(first.preferences.lanDiscovery,false);
  assert.equal(original.lanDiscovery.active,false);
  assert.deepEqual(original.bootstrap.verifiedPeers,[]);
  assert.equal((await fixture(a,'lan_sockets')).count,0);
  const wanted={...first.preferences,lanDiscovery:true};
  await fixture(a,'state_failure',{enabled:true});
  const failed=await fixture(a,'rpc',{method:'configure_network',request:{expectedRevision:0,preferences:wanted}});
  assert.equal(failed.error?.code,'unavailable');
  assert.equal(failed.result,undefined);
  // Real multicast activity occurs while failed-save isolation is checked.
  await fixture(attacker,'advertise_mdns',{address:`/ip4/${b.ip}/tcp/4001/p2p/${b.peer}`});
  assert.equal((await fixture(a,'lan_sockets')).count,0,'failed persistence cannot open mDNS sockets');
  assert.equal((await info(a)).lanDiscovery.active,false);
  assert.deepEqual((await info(a)).bootstrap.verifiedPeers,[]);
  await fixture(a,'state_failure',{enabled:false});
  const saved=await call(a,'configure_network',{expectedRevision:0,preferences:wanted});
  assert.equal(saved.revision,1);assert.deepEqual(saved.preferences,wanted);
  const has=(value,peer)=>value.bootstrap.verifiedPeers.some(p=>p.peerId===peer);
  const found=await until('fresh LAN peers authenticate without hints',async()=>{const v=await info(a);return has(v,b.peer)?v:null;});
  evidence.lanDiscovery.joined=found;
  await until('reciprocal LAN signature',async()=>has(await info(b),a.peer));
  assert.equal(found.lanDiscovery.active,true);
  assert.equal(found.bootstrap.networkDomain,'ae2e3182ade817a3e726c29ef308eed15c6ec267ffc01a68da990e576fa0df18');
  assert.equal(found.bootstrap.verifiedPeers.find(p=>p.peerId===b.peer).rootId,(await snapshot(b)).identity.networkId);
  assert.deepEqual((await snapshot(a)).conversations,[]);
  assert.deepEqual((await snapshot(b)).conversations,[]);
  assert.deepEqual((await call(a,'network_settings')).preferences.bootstrapPeers,[]);
  assert.ok((await fixture(a,'lan_sockets')).count>0);
  assert.equal((await fixture(silent,'lan_sockets')).count,0);
  assert.deepEqual((await info(silent)).bootstrap.verifiedPeers,[]);
  assert.equal((await call(a,'configure_network',{expectedRevision:0,preferences:wanted})).revision,1);
  assert.ok(has(await info(a),b.peer),'same-value retry must not tear down the working connection');
  const invitation=await call(b,'create_invitation');
  const group=(await call(a,'add_contact',{name:'Bob',invitation})).id;
  await until('LAN contact Welcome',async()=>(await snapshot(b)).conversations.some(c=>c.id===group));
  await send(a,b,group,'Found on the same LAN without a bootstrap server','lan-first',1);
  // Independent DNS encoding advertises a real endpoint with another real node's PeerID.
  // The endpoint is reachable, so rejecting the forgery must use transport identity checks.
  const beforeSpoof=await info(a);
  await fixture(silent,'advertise_mdns',{address:`/ip4/${silent.ip}/tcp/4001/p2p/${late.peer}`});
  await until('forged mDNS hint attempted but not authenticated',async()=>{
    const v=await info(a);return v.lanDiscovery.peers.includes(late.peer)&&v.bootstrap.failedAttempts>beforeSpoof.bootstrap.failedAttempts;
  });
  const attacked=await info(a);
  evidence.lanDiscovery.forgery=attacked;
  assert.ok(!has(attacked,late.peer));assert.ok(!has(attacked,silent.peer));
  assert.deepEqual((await snapshot(a)).identity,identity);
  await send(b,a,group,'Unsigned LAN advertisements cannot replace our contact','lan-after-spoof',2);
  const off={...wanted,lanDiscovery:false};
  const disabled=await call(a,'configure_network',{expectedRevision:1,preferences:off});
  assert.equal(disabled.revision,2);assert.deepEqual(disabled.preferences,off);
  await until('disabled LAN sockets close',async()=>(await fixture(a,'lan_sockets')).count===0);
  assert.deepEqual((await info(a)).lanDiscovery.peers,[]);
  await fixture(late,'stop');await start(late,['--lan-discovery'],['tcp']);
  await until('enabled neighbor finds later peer',async()=>has(await info(b),late.peer));
  assert.ok(!has(await info(a),late.peer),'disabled node cannot use later multicast advertisements');
  await fixture(a,'stop');
  const restored=await start(a,['--lan-discovery'],['tcp']);
  assert.equal(restored.peerId,original.peerId);assert.deepEqual(restored.listeners,original.listeners);
  assert.equal(restored.lanDiscovery.active,false,'saved opt-out replaces CLI opt-in');
  assert.equal((await fixture(a,'lan_sockets')).count,0);
  assert.deepEqual((await call(a,'network_settings')).preferences,off);
  assert.deepEqual((await snapshot(a)).identity,identity);
  await send(b,a,group,'Saved LAN opt-out preserves existing encrypted chat after restart','lan-after-restart',3);
  evidence.lanDiscovery.restored=restored;
  const provider=await container('lan-relay',lan);await start(provider,['--relay-server'],['tcp']);
  const relayOnly={...wanted,relayOnly:true,relays:[`/ip4/${provider.ip}/tcp/4001/p2p/${provider.peer}`]};
  const blocked=await call(a,'configure_network',{expectedRevision:2,preferences:relayOnly});
  assert.equal(blocked.revision,3);assert.deepEqual(blocked.preferences,relayOnly);
  assert.deepEqual(blocked.status.lanDiscovery,{enabled:true,active:false,blockedByPolicy:true,peers:[]});
  await until('relay-only configuration has actual reservation',async()=>(await info(a)).relayRoutes.length===1);
  await fixture(silent,'advertise_mdns',{address:`/ip4/${silent.ip}/tcp/4001/p2p/${silent.peer}`});
  await until('positive LAN control learns the newly advertised real peer',async()=>has(await info(b),silent.peer));
  assert.equal((await fixture(a,'lan_sockets')).count,0,'relay-only suppresses actual mDNS despite owner opt-in');
  const policy=await info(a);assert.deepEqual(policy.lanDiscovery.peers,[]);assert.equal(policy.lanDiscovery.active,false);
  assert.ok(!has(policy,silent.peer),'relay-only cannot authenticate a new multicast hint');
  evidence.lanDiscovery.relayOnly=policy;
  for(const node of [a,b,silent,late,provider])await fixture(node,'stop');
  evidence.outcomes.push('Fresh isolated LAN peers discover and authenticate through actual mDNS without seeds; forged hints cannot replace identity; failed save and persisted opt-out keep multicast disabled while real encrypted chat survives restart');
}
